import type { SynthesisBundle } from "@splice/contracts";

function slugify(text: string): string {
  return (
    text
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-|-$/g, "") || "splice-app"
  );
}

export interface ExportedProjectArchive {
  format: "splice-vite-typescript-v1";
  exportedAt: string;
  projectTitle: string;
  bundleId: string;
  revision: number;
  mode: "live" | "replay";
  enginePaths: string[];
  generatedPaths: string[];
  manifest: {
    name: string;
    description: string;
    dependencies: Record<string, string>;
    scripts: Record<string, string>;
  };
  provenance: {
    generator: string;
    statement: string;
    engineIsolation: string;
  };
  files: Record<string, string>;
}

export function serializeProjectArchive(
  bundle: SynthesisBundle,
  projectTitle: string = bundle.app_title || "Splice Fused App"
): ExportedProjectArchive {
  const slug = slugify(projectTitle);

  const packageJson = JSON.stringify(
    {
      name: slug,
      version: "1.0.0",
      private: true,
      type: "module",
      scripts: {
        dev: "vite",
        build: "tsc && vite build",
        preview: "vite preview",
      },
      dependencies: {
        ...bundle.dependencies,
        react: "^18.3.1",
        "react-dom": "^18.3.1",
      },
      devDependencies: {
        vite: "^5.4.11",
        "@vitejs/plugin-react": "^4.3.4",
        typescript: "^5.6.3",
        "@types/react": "^18.3.12",
        "@types/react-dom": "^18.3.1",
      },
    },
    null,
    2
  );

  const viteConfig = `import { defineConfig } from "vite";
import react from "@vitejs/plugin-react";

// Generated by Splice Clean-Room Studio
export default defineConfig({
  plugins: [react()],
});
`;

  const readme = `# ${projectTitle}

${bundle.app_description}

## Clean-Room Provenance & Verification
Generated by **Splice Clean-Room IDE** (HackOHIO 2026).

- **Bundle ID:** \`${bundle.bundle_id}\`
- **Revision:** \`${bundle.revision}\`
- **Execution Mode:** \`${bundle.mode}\`
- **Engine Isolation:** All engine implementations under \`src/engines/\` were synthesized exclusively from formal specifications extracted by Engineer 2 and verified against original desktop application bytecodes via differential oracles. The implementation model never viewed decompiled source.

### Verified Engines
${bundle.engine_paths.map((p) => `- \`${p}\``).join("\n")}

## Quick Start (Run Locally)
\`\`\`bash
npm install
npm run dev
\`\`\`
`;

  const filesRecord: Record<string, string> = {
    "/package.json": packageJson,
    "/vite.config.ts": viteConfig,
    "/README.md": readme,
  };

  for (const [filePath, content] of Object.entries(bundle.files)) {
    filesRecord[filePath] = content;
  }

  return {
    format: "splice-vite-typescript-v1",
    exportedAt: new Date().toISOString(),
    projectTitle,
    bundleId: bundle.bundle_id,
    revision: bundle.revision,
    mode: bundle.mode,
    enginePaths: bundle.engine_paths,
    generatedPaths: bundle.generated_paths,
    manifest: {
      name: slug,
      description: bundle.app_description,
      dependencies: bundle.dependencies,
      scripts: {
        dev: "vite",
        build: "tsc && vite build",
        preview: "vite preview",
      },
    },
    provenance: {
      generator: "Splice Clean-Room Workbench",
      statement:
        "Engines were implemented from specifications verified against original application bytecodes with zero human contamination.",
      engineIsolation: "Strict clean-room isolation; model never accessed decompiled source.",
    },
    files: filesRecord,
  };
}

export function exportProjectBundle(
  bundle: SynthesisBundle,
  projectTitle: string = bundle.app_title || "Splice Fused App"
): void {
  const archive = serializeProjectArchive(bundle, projectTitle);
  const slug = slugify(projectTitle);

  if (
    typeof document === "undefined" ||
    typeof URL === "undefined" ||
    typeof URL.createObjectURL !== "function"
  ) {
    return;
  }

  const jsonString = JSON.stringify(archive, null, 2);
  const blob = new Blob([jsonString], { type: "application/json" });
  const url = URL.createObjectURL(blob);

  const anchor = document.createElement("a");
  anchor.href = url;
  anchor.download = `${slug}-rev${bundle.revision}.splice.json`;
  anchor.rel = "noopener";
  document.body.appendChild(anchor);
  anchor.click();
  document.body.removeChild(anchor);

  setTimeout(() => {
    URL.revokeObjectURL(url);
  }, 1000);
}

export function exportZip(bundle: SynthesisBundle): void {
  exportProjectBundle(bundle, bundle.app_title);
}

/** Downloads the raw bundle JSON (used by the legacy Studio panel). */
export function exportBundleJson(bundle: SynthesisBundle): void {
  if (typeof document === "undefined") return;
  const blob = new Blob([JSON.stringify(bundle, null, 2)], { type: "application/json" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `${slugify(bundle.app_title)}-rev${bundle.revision}.json`;
  a.click();
  URL.revokeObjectURL(url);
}
