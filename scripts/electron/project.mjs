/**
 * Generic Electron project assembly for a behaviorally reconstructed app.
 *
 * The only target-specific artifacts are the modules the orchestration agent writes from oracle
 * observations. This module owns everything else: main-process IPC wiring, the preload bridge, the
 * renderer, packaging metadata, and the reconstruction report. It never copies source files from
 * the original archive.
 */
import fs from "node:fs";
import fsp from "node:fs/promises";
import path from "node:path";

const METADATA = new Set(["contract.json", "TASK.md", "NOTES.md", "public-cases.json", "opencode.json", "events.jsonl"]);

function within(root, relative) {
  if (typeof relative !== "string" || !relative || path.isAbsolute(relative)) throw new Error(`Invalid project path: ${relative}`);
  const resolved = path.resolve(root, relative);
  if (resolved !== root && !resolved.startsWith(`${root}${path.sep}`)) throw new Error(`Path leaves the project: ${relative}`);
  return resolved;
}

function paramType(sample) {
  if (typeof sample === "number") return "number";
  if (typeof sample === "boolean") return "boolean";
  if (Array.isArray(sample)) return "json";
  if (sample && typeof sample === "object") return "json";
  return "string";
}

function channelView(channel, entry) {
  const samples = (entry.args ?? []).find(args => Array.isArray(args) && args.length) ?? [];
  const params = (entry.params ?? []).map((param, index) => ({
    name: param.name || `argument ${index + 1}`,
    type: param.type || paramType(samples[index]),
    example: param.example ?? samples[index] ?? null,
  }));
  for (let index = params.length; index < samples.length; index++)
    params.push({ name: `argument ${index + 1}`, type: paramType(samples[index]), example: samples[index] });
  return {
    channel,
    feature: String(entry.feature ?? "").replaceAll("\\", "/"),
    title: entry.title || channel,
    description: entry.description || "",
    params,
  };
}

export function validateWorkspace(workspace, analysis, contract) {
  workspace = path.resolve(workspace);
  const problems = [];
  if (!contract || typeof contract !== "object") return ["No contract was declared"];
  for (const [channel, entry] of Object.entries(contract.channels ?? {})) {
    const feature = entry.feature;
    if (!feature) { problems.push(`${channel}: contract entry has no feature module`); continue; }
    let file;
    try { file = within(workspace, feature); }
    catch (error) { problems.push(`${channel}: ${error.message}`); continue; }
    if (!/\.(cjs|js)$/.test(file)) problems.push(`${channel}: feature module must be .cjs or .js`);
    if (!fs.existsSync(file)) problems.push(`${channel}: feature module ${feature} does not exist`);
  }
  const declared = new Set(Object.keys(contract.channels ?? {}));
  for (const entry of analysis.ipc.handles ?? [])
    if (!declared.has(entry.channel)) problems.push(`${entry.channel}: original IPC channel is not declared`);
  return problems;
}

async function copyWorkspace(workspace, target) {
  async function walk(directory, prefix) {
    for (const entry of await fsp.readdir(directory, { withFileTypes: true })) {
      const relative = prefix ? `${prefix}/${entry.name}` : entry.name;
      if (!prefix && METADATA.has(entry.name)) continue;
      if (entry.name.startsWith(".") || entry.name === "node_modules") continue;
      const source = path.join(directory, entry.name);
      if (entry.isDirectory()) { await fsp.mkdir(within(target, relative), { recursive: true }); await walk(source, relative); }
      else if (entry.isFile()) {
        const destination = within(target, relative);
        await fsp.mkdir(path.dirname(destination), { recursive: true });
        await fsp.copyFile(source, destination);
      }
    }
  }
  await walk(workspace, "");
}

const MAIN_TEMPLATE = `"use strict";
// Generated by the Splice Electron reconstruction pipeline. Original source is not included.
const { app, BrowserWindow, ipcMain, session, shell } = require("electron");
const path = require("path");
const fs = require("node:fs/promises");
const manifest = require("./reconstruction.json");

const features = manifest.channels.map(entry => ({
  ...entry,
  handle: (() => {
    const loaded = require(path.join(__dirname, entry.feature));
    return typeof loaded === "function" ? loaded : loaded.handle;
  })(),
}));

function context() {
  return { app, fs, path, userData: app.getPath("userData"), documents: app.getPath("documents") };
}

app.whenReady().then(() => {
  for (const entry of features)
    ipcMain.handle(entry.channel, (_event, ...args) => entry.handle(args, context()));

  session.defaultSession.setPermissionRequestHandler((_contents, _permission, callback) => callback(false));
  const window = new BrowserWindow({
    width: 1040,
    height: 760,
    backgroundColor: "#0f172a",
    webPreferences: {
      preload: path.join(__dirname, "preload.cjs"),
      contextIsolation: true,
      nodeIntegration: false,
      sandbox: true,
    },
  });
  window.webContents.setWindowOpenHandler(({ url }) => {
    if (/^https?:/i.test(url)) shell.openExternal(url);
    return { action: "deny" };
  });
  window.webContents.on("will-navigate", event => event.preventDefault());
  window.loadFile(path.join(__dirname, "index.html"));
});

app.on("window-all-closed", () => { if (process.platform !== "darwin") app.quit(); });
`;

function preloadTemplate(channels, name) {
  return `"use strict";
// Sandboxed preload: only Electron modules are available here, so the channel list is inlined.
const { contextBridge, ipcRenderer } = require("electron");
const channels = ${JSON.stringify(channels.map(({ channel, title, description, params }) => ({ channel, title, description, params })), null, 2)};
contextBridge.exposeInMainWorld("splice", {
  manifest: { name: ${JSON.stringify(name)}, channels },
  invoke: (channel, args) => ipcRenderer.invoke(channel, ...(Array.isArray(args) ? args : [])),
});
`;
}

