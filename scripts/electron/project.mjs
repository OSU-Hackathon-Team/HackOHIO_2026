export async function assembleProject({ analysis, contract, workspace, output, extraFiles = {} }) {
  workspace = path.resolve(workspace);
  const target = path.resolve(output);
  await fsp.rm(target, { recursive: true, force: true });
  await fsp.mkdir(target, { recursive: true });
  const channels = (analysis.ipc.handles ?? []).map(entry => channelView(entry.channel, contract.channels?.[entry.channel] ?? {}));
  const declared = new Set(channels.map(entry => entry.channel));
  for (const [channel, entry] of Object.entries(contract.channels ?? {}))
    if (!declared.has(channel)) channels.push(channelView(channel, entry));
  for (const entry of channels) if (!entry.feature) throw new Error(`${entry.channel}: no feature module declared`);

  await copyWorkspace(workspace, target);
  for (const entry of channels) {
    const source = within(workspace, entry.feature);
    const destination = within(target, entry.feature);
    if (!fs.existsSync(source)) throw new Error(`${entry.channel}: feature module ${entry.feature} does not exist`);
    await fsp.mkdir(path.dirname(destination), { recursive: true });
    await fsp.copyFile(source, destination);
  }

  const manifest = {
    schema_version: 1,
    method: "behavioral reconstruction from black-box IPC observations",
    source: { name: analysis.archive?.name ?? null, version: analysis.archive?.version ?? null,
      sha256: analysis.archive?.sha256 ?? null },
    channels,
    parity: {
      level: "bounded-original-ipc",
      original_ipc_channels: channels.map(entry => entry.channel),
      note: "Every original IPC handler is registered and checked against the original archive on generated public and held-out cases. Storage and UI behavior is matched only where those cases exercised it.",
    },
  };
  const baseName = String(analysis.archive?.name ?? "electron-app").toLowerCase().replace(/[^a-z0-9-]+/g, "-");
  const files = {
    "package.json": JSON.stringify({
      name: `${baseName.replace(/^-+|-+$/g, "") || "electron-app"}-reconstructed`,
      version: "1.0.0", private: true, main: "main.cjs",
      scripts: { start: "electron ." },
      devDependencies: { electron: "45.0.0" },
    }, null, 2) + "\n",
    "main.cjs": MAIN_TEMPLATE,
    "preload.cjs": preloadTemplate(channels, baseName || "reconstructed-app"),
    "index.html": HTML_TEMPLATE.replace("<title>Reconstructed app</title>", `<title>${manifest.source.name ?? "Reconstructed app"}</title>`),
    "renderer.js": RENDERER_TEMPLATE,
    "style.css": STYLE_TEMPLATE,
    "reconstruction.json": JSON.stringify(manifest, null, 2) + "\n",
    "analysis.json": JSON.stringify(analysis, null, 2) + "\n",
    ...extraFiles,
  };
  for (const [file, content] of Object.entries(files)) {
    const destination = within(target, file);
    await fsp.mkdir(path.dirname(destination), { recursive: true });
    if (!fs.existsSync(destination)) await fsp.writeFile(destination, content);
  }
  await fsp.writeFile(path.join(target, "README.md"), `# ${manifest.source.name ?? "Reconstructed Electron app"}\n\n` +
    `Reconstructed from a packaged Electron archive (sha256 \`${manifest.source.sha256}\`) by observing its IPC behavior. ` +
    "The app implements every original IPC channel with new code; original source files are not included.\n\n" +
    "```bash\nnpm install\nnpm start\n```\n\n" +
    "Verification is bounded: the generated cases compare handler results, errors and persisted files against the " +
    "original archive. Case values are not a proof of equivalence for arbitrary input.\n");
  return { output: target, manifest, files: Object.keys(files) };
}
